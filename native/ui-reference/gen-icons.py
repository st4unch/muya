#!/usr/bin/env python3
"""Generate native/app/Sources/Theme/IconData.swift from src/redesign/icons.tsx (path/circle/rect data, stroke width and
default size of every icon). The drawing code (SVG path -> NSBezierPath) is hand-written in Icons.swift.
  python3 native/ui-reference/gen-icons.py
"""
import os, re
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = "src/redesign/icons.tsx"
text = open(os.path.join(ROOT, SRC)).read()
lines = text.splitlines()
out = ["// GENERATED by native/ui-reference/gen-icons.py from src/redesign/icons.tsx — do not edit by hand.",
       "// 24x24 viewBox, round caps/joins, stroke only (the web icons are all outline icons). Cases are the web component names minus 'Icon'.",
       "import CoreGraphics", "",
       "public enum ThemeIconShape {",
       "    case path(String)",
       "    case circle(cx: CGFloat, cy: CGFloat, r: CGFloat)",
       "    case rect(x: CGFloat, y: CGFloat, w: CGFloat, h: CGFloat, rx: CGFloat)",
       "}", "",
       "public struct ThemeIconDef {",
       "    public let size: CGFloat      // default point size in the web UI",
       "    public let stroke: CGFloat    // stroke width in 24-unit viewBox coordinates",
       "    public let shapes: [ThemeIconShape]",
       "}", "",
       "public enum ThemeIcon: String, CaseIterable {"]
icons = []
for m in re.finditer(r"export function (\w+)Icon\(\{ size = ([\d.]+), \.\.\.p \}: IconProps\) \{(.*?)\n\}", text, re.S):
    name, size, body = m.group(1), m.group(2), m.group(3)
    sw = re.search(r"base\(size, ([\d.]+), p\)", body).group(1)
    line = text[: m.start()].count("\n") + 1
    shapes = []
    for el in re.finditer(r"<(path|circle|rect)\s+([^>]*?)/>", body, re.S):
        kind, attrs = el.group(1), dict(re.findall(r'(\w+)="([^"]*)"', el.group(2)))
        if kind == "path":
            shapes.append(f'.path("{attrs["d"]}")')
        elif kind == "circle":
            shapes.append(f'.circle(cx: {attrs["cx"]}, cy: {attrs["cy"]}, r: {attrs["r"]})')
        else:
            shapes.append(f'.rect(x: {attrs["x"]}, y: {attrs["y"]}, w: {attrs["width"]}, h: {attrs["height"]}, rx: {attrs.get("rx", "0")})')
    icons.append((name[0].lower() + name[1:], size, sw, shapes, line))
# Icons the web draws inline (not in icons.tsx): Stop = a rounded square (SessionHeader.tsx, drawn there as a filled rect; a thick outline here).
icons.append(("stop", "12", "3", ['.rect(x: 6, y: 6, w: 12, h: 12, rx: 2.5)'], 0))
for n, *_ in icons:
    out.append(f"    case {n}")
out += ["", "    public var def: ThemeIconDef {", "        switch self {"]
for n, size, sw, shapes, line in icons:
    out.append(f"        case .{n}: return ThemeIconDef(size: {size}, stroke: {sw}, shapes: [{', '.join(shapes)}]) // " + (f"{SRC}:{line}" if line else "src/redesign/SessionHeader.tsx (inline svg)"))
out += ["        }", "    }", "}"]
dst = os.path.join(ROOT, "native/app/Sources/Theme/IconData.swift")
open(dst, "w").write("\n".join(out) + "\n")
print("wrote", dst, len(icons), "icons")
