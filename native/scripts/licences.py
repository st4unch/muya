#!/usr/bin/env python3
"""Licence listing of the native workspace's third-party code (cargo metadata, no network tools).

  licences.py notices   print THIRD_PARTY_NOTICES.md
  licences.py check     exit 1 on an unknown licence; list copyleft deps explicitly
"""
import json, re, subprocess, sys, pathlib

NATIVE = pathlib.Path(__file__).resolve().parent.parent
# Ghostty / libghostty-vt is built by zig outside cargo's view: listed by hand (progress doc S2 ext).
EXTRA = [
    ("libghostty-vt (Ghostty core)", "pinned commit a887df4", "MIT", "https://github.com/ghostty-org/ghostty"),
    ("Highway", "vendored in Ghostty", "Apache-2.0 OR BSD-3-Clause", "https://github.com/google/highway"),
    ("simdutf", "vendored in Ghostty", "Apache-2.0 OR MIT", "https://github.com/simdutf/simdutf"),
    ("Zig compiler_rt", "linked by Ghostty build", "MIT", "https://github.com/ziglang/zig"),
    # UI fonts bundled in MuyaNative.app (native/app/Resources/Fonts, licence texts next to them) and the icon set.
    ("IBM Plex Sans (font)", "@fontsource 5.x", "OFL-1.1", "https://github.com/IBM/plex"),
    ("JetBrains Mono (font)", "@fontsource 5.x", "OFL-1.1", "https://github.com/JetBrains/JetBrainsMono"),
    ("Lucide icons", "lucide-react 0.546", "ISC", "https://github.com/lucide-icons/lucide"),
]
OK = {"MIT", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "ISC", "Zlib", "Unicode-3.0", "Unicode-DFS-2016",
      "0BSD", "CDLA-Permissive-2.0", "CC0-1.0", "Unlicense", "MPL-2.0", "BSL-1.0", "LLVM-exception", "Apache-2.0 WITH LLVM-exception"}
COPYLEFT = re.compile(r"\b(A?GPL|LGPL)", re.I)

def deps():
    meta = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--manifest-path", str(NATIVE / "Cargo.toml")],
        stderr=subprocess.DEVNULL))
    ws = set(meta["workspace_members"])
    for p in sorted(meta["packages"], key=lambda p: (p["name"], p["version"])):
        if p["id"] in ws: continue
        yield p["name"], p["version"], (p.get("license") or ("file:" + p["license_file"] if p.get("license_file") else "")), p.get("repository") or ""

def terms(expr):
    return [t for t in re.split(r"[\s()/]+|\bAND\b|\bOR\b|\bWITH\b", expr) if t]

def verdict(expr):
    """unknown | copyleft | ok. An OR expression is fine when ANY alternative is permissive."""
    if not expr or expr.startswith("file:"): return "unknown"
    alts = [a.strip(" ()") for a in re.split(r"\bOR\b", expr)] if " OR " in expr else [expr]
    if any(all(t in OK for t in terms(a)) for a in alts): return "ok"
    if COPYLEFT.search(expr) and not any(all(t in OK for t in terms(a)) for a in alts): 
        return "copyleft" if any(COPYLEFT.search(a) for a in alts) else "unknown"
    return "unknown"

def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else "check"
    rows = list(deps()) + [(n, v, l, u) for n, v, l, u in EXTRA]
    if mode == "notices":
        print("# Third-party notices\n\nGenerated by `native/scripts/notices.sh` from `cargo metadata`; do not edit.\n")
        print("Muya's own code is MIT. The Swift app uses system frameworks only (no Swift packages).\n")
        print("| Component | Version | Licence | Source |\n|---|---|---|---|")
        for n, v, l, u in rows: print(f"| {n} | {v} | {l or 'UNKNOWN'} | {u} |")
        return 0
    bad = [r for r in rows if verdict(r[2]) == "unknown"]
    cl = [r for r in rows if verdict(r[2]) == "copyleft"]
    print(f"licence-check: {len(rows)} third-party components")
    for n, v, l, _ in cl: print(f"  COPYLEFT {n} {v}: {l}  (operator decision: GPL/AGPL/LGPL)")
    for n, v, l, _ in bad: print(f"  UNKNOWN  {n} {v}: {l or '(none)'}")
    print(f"licence-check: {len(cl)} copyleft, {len(bad)} unknown")
    return 1 if bad else 0

sys.exit(main())
